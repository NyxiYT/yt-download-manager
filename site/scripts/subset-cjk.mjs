// The marquee writes "Download" in Japanese (ダウンロード) and Chinese (下载). Instead of loading a CJK font,
// this cuts Noto Sans JP and SC (OFL-1.1, from Fontsource) down to exactly those glyphs, once, into
// public/fonts, with the @font-face rules in src/styles/cjk.css. Run it again only if the words change: npm run fonts:cjk
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import subsetFont from 'subset-font';

const require = createRequire(import.meta.url);
const WORDS = [
  { pkg: '@fontsource/noto-sans-jp', family: 'Download JA', text: 'ダウンロード', out: 'download-ja' },
  { pkg: '@fontsource/noto-sans-sc', family: 'Download ZH', text: '下载', out: 'download-zh' },
];
const WEIGHT = 600;

// Fontsource splits CJK fonts into numbered files, each with its unicode-range; find the files holding our glyphs.
function chunksFor(css, text) {
  const faces = [...css.matchAll(/@font-face\s*{([^}]*)}/g)].map((m) => m[1]);
  const found = new Map();
  for (const ch of new Set(text)) {
    const cp = ch.codePointAt(0);
    const face = faces.find((f) => {
      const range = /unicode-range:\s*([^;]+);/.exec(f)?.[1] ?? '';
      return range.split(',').some((r) => {
        const [a, b] = r.trim().replace(/^U\+/i, '').split('-').map((x) => parseInt(x, 16));
        return cp >= a && cp <= (Number.isNaN(b) || b === undefined ? a : b);
      });
    });
    if (!face) throw new Error(`no file covers ${ch}`);
    const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(face)[1];
    found.set(file, (found.get(file) ?? '') + ch);
  }
  return found;
}

const outDir = new URL('../public/fonts/', import.meta.url);
await mkdir(outDir, { recursive: true });
const css = [];
for (const w of WORDS) {
  const root = dirname(require.resolve(`${w.pkg}/package.json`));
  const sheet = await readFile(join(root, `${WEIGHT}.css`), 'utf8');
  let i = 0;
  for (const [file, chars] of chunksFor(sheet, w.text)) {
    const src = await readFile(join(root, 'files', file));
    const font = await subsetFont(src, chars, { targetFormat: 'woff2' });
    const name = `${w.out}-${i++}.woff2`;
    await writeFile(new URL(name, outDir), font);
    const range = [...chars].map((c) => `U+${c.codePointAt(0).toString(16).toUpperCase()}`).join(', ');
    css.push(`@font-face { font-family: '${w.family}'; font-style: normal; font-weight: ${WEIGHT}; font-display: swap; src: url('/fonts/${name}') format('woff2'); unicode-range: ${range}; }`);
    console.log(`${name}: ${chars} (${font.length} bytes)`);
  }
}
await writeFile(new URL('../src/styles/cjk.css', import.meta.url), `/* Generated by scripts/subset-cjk.mjs. Do not edit. */\n${css.join('\n')}\n`);
console.log('Rules written to src/styles/cjk.css.');
